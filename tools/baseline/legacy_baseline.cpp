// Records reference values from the QTsignalApp 6.14 sources (the "legacy" code).
//
// Build against the legacy src/ and include/ folders plus the tiny Qt stand-in in
// qtshim/ (no Qt needed), then run once:
//   legacy_baseline > tests/fixtures/legacy_baseline.inc
// The parity tests replay tests/fixtures/scenarios.h on the new core and compare.

#include "antenna_validation_bench.h"
#include "electrostatic_model.h"
#include "em_calculator_model.h"
#include "fdtd_solver.h"
#include "magnetostatic_model.h"
#include "numerical_em_solvers.h"

#include "scenarios.h"

#include <cstdio>
#include <string>
#include <vector>

// moc normally generates these signal bodies.
void ElectrostaticModel::changed() {}
void MagnetostaticModel::changed() {}

namespace
{
std::vector<double> values;
void put(double v)
{
    values.push_back(v);
}
void flush(const char *name)
{
    std::printf("inline constexpr double %s[] = {\n", name);
    for (std::size_t i = 0; i < values.size(); ++i)
        std::printf("    %.17g,%s", values[i], (i % 4 == 3 || i + 1 == values.size()) ? "\n" : "");
    std::printf("};\n\n");
    values.clear();
}
} // namespace

int main()
{
    std::printf("// Generated by tools/baseline/legacy_baseline.cpp from the QTsignalApp 6.14 sources.\n"
                "// Do not edit by hand. Values printed with %%.17g.\n#pragma once\n\n");

    // Electrostatics: each source alone, then the whole scene, at every probe point.
    const auto eSources = scenarios::electrostaticSources<ElectrostaticSource>();
    auto putE = [](const ElectrostaticFieldResult &r)
    {
        put(r.electricField.x);
        put(r.electricField.y);
        put(r.electricField.z);
        put(r.potential);
        put(r.potentialDefined ? 1.0 : 0.0);
        put(r.singular ? 1.0 : 0.0);
    };
    for (const auto &s : eSources)
    {
        ElectrostaticModel model;
        model.addSource(s);
        for (const auto &p : scenarios::probePoints()) putE(model.fieldAt({p[0], p[1], p[2]}));
    }
    {
        ElectrostaticModel model;
        for (const auto &s : eSources) model.addSource(s);
        for (const auto &p : scenarios::probePoints()) putE(model.fieldAt({p[0], p[1], p[2]}));
    }
    flush("kLegacyElectrostatic");

    // Magnetostatics, same layout.
    const auto mSources = scenarios::magnetostaticSources<MagnetostaticSource>();
    auto putM = [](const MagnetostaticFieldResult &r)
    {
        put(r.magneticFluxDensity.x);
        put(r.magneticFluxDensity.y);
        put(r.magneticFluxDensity.z);
        put(r.singular ? 1.0 : 0.0);
    };
    for (const auto &s : mSources)
    {
        MagnetostaticModel model;
        model.addSource(s);
        for (const auto &p : scenarios::probePoints()) putM(model.fieldAt({p[0], p[1], p[2]}));
    }
    {
        MagnetostaticModel model;
        for (const auto &s : mSources) model.addSource(s);
        for (const auto &p : scenarios::probePoints()) putM(model.fieldAt({p[0], p[1], p[2]}));
    }
    flush("kLegacyMagnetostatic");

    // FDTD: probe samples and energy after N steps.
    for (const auto &c : scenarios::fdtdCases())
    {
        FDTD::Solver2D solver;
        scenarios::setupFdtd(solver, c);
        solver.step(c.steps);
        for (const auto &pr : scenarios::fdtdProbes())
        {
            const auto s = solver.sample(pr[0], pr[1]);
            put(s.ezVPerM);
            put(s.hzAPerM);
            put(s.exVPerM);
            put(s.hxAPerM);
        }
        put(solver.totalEnergyPerMeterJ());
    }
    flush("kLegacyFdtd");

    // Wire-network MoM.
    for (const auto &in : scenarios::wireCases())
    {
        const auto r = NumericalEM::solveWireNetworkMom(in);
        put(r.valid ? 1.0 : 0.0);
        put(r.feeds.empty() ? 0.0 : r.feeds.front().activeImpedanceOhm.real());
        put(r.feeds.empty() ? 0.0 : r.feeds.front().activeImpedanceOhm.imag());
        put(r.directivityDbi);
    }
    flush("kLegacyWireNetwork");

    // 2D BEM capacitance and loop coupling.
    {
        NumericalEM::BemInput2D bem;
        bem.conductorA.center = {-0.02, 0.0};
        bem.conductorB.center = {0.025, 0.004};
        bem.conductorB.shape = NumericalEM::ConductorShape::Rectangle;
        bem.conductorA.potentialV = 0.5;
        bem.conductorB.potentialV = -0.5;
        bem.epsilonR = 2.2;
        const auto r = NumericalEM::solveTwoConductorBem2D(bem);
        put(r.valid ? 1.0 : 0.0);
        put(r.capacitancePerLengthFpm);
        NumericalEM::LoopCouplingInput lc;
        lc.secondary.center = {0.0, 0.03, 0.04};
        lc.secondary.axis = {0.0, 0.3, 1.0};
        lc.secondary.turns = 3;
        const auto l = NumericalEM::solveCircularLoopCoupling(lc);
        put(l.valid ? 1.0 : 0.0);
        put(l.mutualInductanceH);
        put(l.primarySelfInductanceH);
        put(l.secondarySelfInductanceH);
        put(l.couplingCoefficient);
    }
    flush("kLegacyBemLoop");

    // Pocklington tab at its UI defaults (15 mm) and with a 1 mm wire: Zin at N = 41.
    for (double radius : {0.015, 0.001})
    {
        NumericalEM::ThinWireMomInput in;
        in.frequencyHz = 100e6;
        in.lengthM = 1.409;
        in.radiusM = radius;
        in.segments = 41;
        const auto r = NumericalEM::solveThinWireDipolePocklington(in);
        put(r.inputImpedanceOhm.real());
        put(r.inputImpedanceOhm.imag());
    }
    flush("kLegacyPocklington");

    // Production validation bench, 100 MHz: first row of each canonical case.
    for (auto kind : {AntennaValidation::CaseKind::HalfWaveDipole, AntennaValidation::CaseKind::SmallCircularLoop,
                      AntennaValidation::CaseKind::QuarterWaveMonopole, AntennaValidation::CaseKind::RectangularPatch})
    {
        const auto report = AntennaValidation::runProductionCase(kind, 100e6);
        const auto &row = report.rows.front();
        put(row.inputImpedanceOhm.real());
        put(row.inputImpedanceOhm.imag());
        put(row.directivityDbi);
        put(static_cast<double>(row.verdict));
    }
    flush("kLegacyValidation");

    for (const char *expression : scenarios::calculatorExpressions())
        put(EmCalculator::evaluateExpression(expression).value);
    flush("kLegacyCalculator");
    return 0;
}
